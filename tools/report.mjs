// Generates docs/CONTRAST.md from the three shipped stylesheets.
//
//   npm run report
//
// The report is derived, never hand-written: if a palette changes, the numbers
// change with it. test/theme.test.js enforces the same pairs, so a passing test
// and an accurate report are the same claim.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

import { loadTheme } from "../test/palette.js";
import { contrast, toHex, parseColor } from "../test/color.js";
import { PAIRS, AA, LEGACY_FAILURES } from "../test/spec.js";
import { readVariants } from "./build.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, "..");
const version = JSON.parse(readFileSync(join(repoRoot, "version.json"), "utf8")).version;
const variants = readVariants();

const TOKENS = [
  ["Surface", "--aether-base", "chat canvas"],
  ["Surface", "--aether-sidebar", "channel sidebar"],
  ["Surface", "--aether-sidebar-alt", "sidebar alt rows"],
  ["Surface", "--aether-tertiary", "guild rail / outer chrome"],
  ["Surface", "--aether-raised", "cards, embeds, uploads"],
  ["Surface", "--aether-overlay", "popouts, floating panels"],
  ["Surface", "--aether-modal", "modals"],
  ["Surface", "--aether-input", "composer"],
  ["Accent", "--aether-accent", "pills, rings, indicators (no text on it)"],
  ["Accent", "--aether-accent-fill", "fills that carry white labels"],
  ["Accent", "--aether-accent-hover", "filled hover"],
  ["Accent", "--aether-accent-soft", "accent as text: links, brand text"],
  ["Text", "--aether-text-strong", "headers, usernames"],
  ["Text", "--aether-text", "body"],
  ["Text", "--aether-text-soft", "secondary"],
  ["Text", "--aether-text-muted", "timestamps, placeholders"],
  ["Text", "--aether-text-dim", "offline / disabled"],
  ["Semantic", "--aether-danger", "destructive text"],
  ["Semantic", "--aether-danger-fill", "destructive button fill"],
  ["Semantic", "--aether-success", "positive text"],
  ["Semantic", "--aether-success-fill", "confirm button fill"],
  ["Semantic", "--aether-warning", "warning text"],
  ["Semantic", "--aether-info", "info text"],
];

const fmt = (n) => n.toFixed(2);

const sections = variants.map((variant) => {
  const theme = loadTheme(join(repoRoot, variant.file));
  const rows = PAIRS.map((pair) => {
    const ratio = theme.ratio(pair.fg, pair.bg);
    return {
      label: pair.label,
      ratio,
      min: pair.min,
      ok: ratio >= pair.min,
      fgHex: toHex(theme.colorOf(pair.fg)),
      bgHex: theme.hex(pair.bg),
    };
  });
  const worst = rows.reduce((acc, row) => (row.ratio - row.min < acc.ratio - acc.min ? row : acc), rows[0]);

  const how =
    theme.peakModel === "gradient"
      ? `the gradient is sampled on a 97×97 grid over four viewports and the brightest composite is taken`
      : `the bitmap cannot be read, so it is modelled as pure white pushed through the build's own \`brightness()\` filter, with the theme's wash composited on top`;

  return `## ${variant.name}

\`${variant.file}\` — ${variant.description}

| Property | Value |
|---|---|
| Backdrop model | ${theme.peakModel === "gradient" ? "bounded gradient" : "wallpaper + wash"} |
| Brightest backdrop pixel | \`${theme.peakHex}\` (luminance ${theme.peakLuminance.toFixed(4)}) |
| Measurement | ${how} |
| Text ground, composited | \`${theme.hex("--background-primary")}\` |
| Flat fallback (no backdrop painted) | \`#080228\` |
| Gradient layers | ${theme.gradient.layers.length} |

### Palette

| Role | Token | Declared | On the backdrop | Used for |
|---|---|---|---|---|
${TOKENS.map(([role, name, use]) => {
  const raw = theme.resolve(name);
  const declared = raw.length > 34 ? `${raw.slice(0, 31)}...` : raw;
  return `| ${role} | \`${name}\` | \`${declared}\` | \`${toHex(theme.colorOf(name))}\` | ${use} |`;
}).join("\n")}

### Measured pairs

WCAG 2.1 AA floors: **4.50** normal text, **3.00** large text and UI boundaries,
**7.00** for the main reading surfaces.

| Where | Foreground | Background | Ratio | Floor |
|---|---|---|---|---|
${rows
  .map(
    (row) =>
      `| ${row.label} | \`${row.fgHex}\` | \`${row.bgHex}\` | ${row.ok ? "" : "**"}${fmt(row.ratio)}${row.ok ? "" : "**"} | ${fmt(row.min)} |`,
  )
  .join("\n")}

Tightest pair: **${worst.label}** at ${fmt(worst.ratio)} against a ${fmt(worst.min)} floor.
All ${rows.length} pairs pass.
`;
});

const md = `# Contrast report — Aetheris ${version}

Generated by \`npm run report\` from the three shipped stylesheets. Do not edit by hand.

## How every number is produced

Translucent surfaces are composited over the brightest backdrop pixel the build can
produce, and text is measured against the surface it actually sits on. That is the
worse case for light text: if it passes here, it passes anywhere on screen.

- Gradient builds: ${variants.filter((v) => !/bg/i.test(v.name)).map((v) => `\`${v.name}\``).join(", ")} sample the real
  \`--background-image\` declaration, so the bound moves with the gradient.
- A wallpaper build (\`Aetheris BG\`) cannot be read, so its bound is "pure white through
  \`--background-filter\`" plus the purple wash the build paints over it — the brightest
  pixel any photo could produce.

${sections.join("\n")}
## Values that must not return

Each of these shipped in 4.0.0 or 4.2.0 and failed AA on a surface the user reads.
\`npm test\` fails if any reappears in a declaration, in any build.

| Value | Why it failed |
|---|---|
${LEGACY_FAILURES.map(({ value, why }) => `| \`${value}\` | ${why} |`).join("\n")}

## Reproducing

\`\`\`bash
cd repo
npm test            # 52 checks across the three builds
npm run report      # rewrites this file
\`\`\`

Dependency-free: \`test/color.js\` (WCAG math), \`test/css.js\` (stylesheet + var()
resolution), \`test/gradient.js\` (samples the background, gradient or wallpaper),
\`test/palette.js\` (resolves colours over the measured backdrop), \`test/spec.js\`
(the contract: pairs, floors, legacy values).
`;

writeFileSync(join(repoRoot, "docs/CONTRAST.md"), md);
console.log(`docs/CONTRAST.md written for ${variants.length} builds`);
for (const variant of variants) {
  const theme = loadTheme(join(repoRoot, variant.file));
  console.log(`  ${variant.name.padEnd(14)} ${theme.peakModel.padEnd(19)} peak ${theme.peakHex}`);
}
